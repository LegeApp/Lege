/// The glyph name an encoding assigns to `code`.
///
/// PDF simple-font encoding is defined code → **name** → glyph; Unicode is
/// not in the loop, and routing through it loses glyphs (AGL's `mu` is
/// U+00B5, not Symbol's U+03BC; Dingbats' `a1`..`a191` have no Unicode names
/// at all) and fails outright for a font whose only name table is `post` —
/// which is every bare CFF we wrap.
pub fn builtin_glyph_name(encoding: BaseEncoding, code: u8) -> Option<&'static [u8]> {
    let table: &[Option<&[u8]>; 224] = match encoding {
        BaseEncoding::SymbolFont => &SYMBOL_NAMES,
        BaseEncoding::ZapfDingbats => &ZAPF_NAMES,
        BaseEncoding::Standard => &STANDARD_NAMES,
        BaseEncoding::WinAnsi => &WINANSI_NAMES,
        BaseEncoding::MacRoman => &MACROMAN_NAMES,
        BaseEncoding::MacExpert => &MACEXPERT_NAMES,
        // A symbolic font with no named encoding is addressed by raw code
        // through its own cmap, not by name.
        BaseEncoding::Symbolic => return None,
    };
    let idx = (code as usize).checked_sub(32)?;
    table.get(idx).copied().flatten()
}

