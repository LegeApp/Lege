//! Simple-font character encodings (fonts.md §2 "Character-code
//! interpretation").
//!
//! Maps a single-byte code to a Unicode scalar so the outline engine's cmap
//! can find the glyph. WinAnsiEncoding is implemented exactly (cp1252);
//! StandardEncoding and MacRomanEncoding are handled for their Latin range with
//! a latin-1 high-byte approximation (full Adobe tables are a later refinement).
//! `/Differences` glyph names resolve through a compact AGL subset plus the
//! algorithmic `uniXXXX` form.

/// A named base encoding from a font's `/Encoding`.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BaseEncoding {
    Standard,
    WinAnsi,
    MacRoman,
    /// MacExpertEncoding (Annex D.4): small caps, oldstyle figures,
    /// superiors/inferiors, fractions and ligatures. Name-only — its glyphs
    /// have expert names, not Unicode identities.
    MacExpert,
    /// No named encoding — use the font's built-in cmap with the raw code
    /// (symbolic fonts).
    Symbolic,
    /// The Symbol face's built-in encoding (Annex D.5).
    SymbolFont,
    /// The ZapfDingbats face's built-in encoding (Annex D.6).
    ZapfDingbats,
}

/// The cp1252 replacements for the `0x80..=0x9F` block; `\0` marks undefined.
const CP1252_HIGH: [char; 32] = [
    '\u{20AC}', '\0', '\u{201A}', '\u{0192}', '\u{201E}', '\u{2026}', '\u{2020}', '\u{2021}',
    '\u{02C6}', '\u{2030}', '\u{0160}', '\u{2039}', '\u{0152}', '\0', '\u{017D}', '\0', '\0',
    '\u{2018}', '\u{2019}', '\u{201C}', '\u{201D}', '\u{2022}', '\u{2013}', '\u{2014}', '\u{02DC}',
    '\u{2122}', '\u{0161}', '\u{203A}', '\u{0153}', '\0', '\u{017E}', '\u{0178}',
];

impl BaseEncoding {
    pub fn from_name(name: &[u8]) -> Option<BaseEncoding> {
        match name {
            b"WinAnsiEncoding" => Some(BaseEncoding::WinAnsi),
            b"StandardEncoding" => Some(BaseEncoding::Standard),
            b"MacRomanEncoding" => Some(BaseEncoding::MacRoman),
            b"MacExpertEncoding" => Some(BaseEncoding::MacExpert),
            _ => None,
        }
    }

    /// The Unicode scalar for `code`, or `None` if undefined in this encoding.
    pub fn to_char(self, code: u8) -> Option<char> {
        match self {
            BaseEncoding::Symbolic => None,
            BaseEncoding::WinAnsi => match code {
                0x20..=0x7E => Some(code as char),
                0x80..=0x9F => {
                    let c = CP1252_HIGH[(code - 0x80) as usize];
                    (c != '\0').then_some(c)
                }
                0xA0..=0xFF => char::from_u32(code as u32),
                _ => None,
            },
            // Standard: ASCII with two typographic swaps; high bytes are the
            // Adobe standard set (approximated as undefined here).
            BaseEncoding::Standard => match code {
                0x27 => Some('\u{2019}'), // quoteright
                0x60 => Some('\u{2018}'), // quoteleft
                0x20..=0x7E => Some(code as char),
                _ => None,
            },
            // MacRoman: ASCII exact; high bytes from the real Mac OS Roman
            // table (PDFium `UnicodeFromAppleRomanCharCode` analog) — the
            // former latin-1 approximation mis-mapped every 0x80–0xFF code.
            BaseEncoding::MacRoman => match code {
                0x20..=0x7E => Some(code as char),
                0x80..=0xFF => Some(MACROMAN_HIGH[(code - 0x80) as usize]),
                _ => None,
            },
            // Expert glyphs (oldstyle figures, small caps, superiors) have
            // *names*, not usable Unicode identities; resolution is by name
            // via `builtin_glyph_name`, matching PDFium (whose MacExpert
            // Unicode table is zeros outside a few slots).
            BaseEncoding::MacExpert => None,
            // The two symbolic standard faces carry their own code tables.
            BaseEncoding::SymbolFont => table_char(&SYMBOL_ENCODING, code),
            BaseEncoding::ZapfDingbats => table_char(&ZAPF_ENCODING, code),
        }
    }
}

