#[cfg(test)]
mod tests {
    #![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]
    use super::*;

    #[test]
    fn full_agl_resolves_tail_names_and_dot_variants() {
        // Names beyond the compact subset resolve via the bundled AGL.
        assert_eq!(glyph_name_to_char(b"aleph"), Some('\u{2135}'));
        assert_eq!(glyph_name_to_char(b"Ohorn"), Some('\u{01A0}'));
        assert_eq!(glyph_name_to_char(b"afii10017"), Some('\u{0410}')); // Cyrillic A
        assert_eq!(glyph_name_to_char(b"longs"), Some('\u{017F}'));
        // AGL suffix rule: `name.suffix` resolves as `name`.
        assert_eq!(glyph_name_to_char(b"aleph.alt1"), Some('\u{2135}'));
        // Unknown names still miss.
        assert_eq!(glyph_name_to_char(b"notarealglyphname"), None);
    }

    #[test]
    fn macexpert_resolves_by_name_only() {
        assert_eq!(
            BaseEncoding::from_name(b"MacExpertEncoding"),
            Some(BaseEncoding::MacExpert)
        );
        // Annex D.4 spot checks (PDFium kMacExpertEncodingNames).
        assert_eq!(
            builtin_glyph_name(BaseEncoding::MacExpert, 0x20),
            Some(&b"space"[..])
        );
        assert_eq!(
            builtin_glyph_name(BaseEncoding::MacExpert, 0x21),
            Some(&b"exclamsmall"[..])
        );
        assert_eq!(
            builtin_glyph_name(BaseEncoding::MacExpert, 0x30),
            Some(&b"zerooldstyle"[..])
        );
        // Expert glyphs have names, not Unicode identities.
        assert_eq!(BaseEncoding::MacExpert.to_char(0x21), None);
        // A gap stays empty.
        assert_eq!(builtin_glyph_name(BaseEncoding::MacExpert, 0x80), None);
    }

    #[test]
    fn winansi_ascii_and_high() {
        assert_eq!(BaseEncoding::WinAnsi.to_char(b'A'), Some('A'));
        assert_eq!(BaseEncoding::WinAnsi.to_char(0x80), Some('\u{20AC}')); // euro
        assert_eq!(BaseEncoding::WinAnsi.to_char(0xE9), Some('é'));
        assert_eq!(BaseEncoding::WinAnsi.to_char(0x81), None); // undefined
    }

    #[test]
    fn differences_names() {
        assert_eq!(glyph_name_to_char(b"A"), Some('A'));
        assert_eq!(glyph_name_to_char(b"space"), Some(' '));
        assert_eq!(glyph_name_to_char(b"uni00E9"), Some('é'));
        assert_eq!(glyph_name_to_char(b"period"), Some('.'));
        assert_eq!(glyph_name_to_char(b"notaglyph"), None);
    }
}
