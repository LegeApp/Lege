/// The Mac OS Roman char code for a Unicode scalar (reverse of the table
/// above; ASCII is identity). PDFium `CharCodeFromUnicodeForEncoding`
/// (`kAppleRoman`) analog — the route into a font whose only cmap is the
/// Macintosh (1,0) subtable.
pub fn macroman_code_for_char(c: char) -> Option<u8> {
    match c {
        '\u{20}'..='\u{7E}' => Some(c as u8),
        _ => MACROMAN_HIGH
            .iter()
            .position(|&m| m == c)
            .map(|i| (i + 0x80) as u8),
    }
}

/// Resolve a PDF glyph name (from `/Differences`) to a Unicode scalar: the
/// algorithmic `uniXXXX`/`uXXXXXX` forms, then a compact standard-name table.
pub fn glyph_name_to_char(name: &[u8]) -> Option<char> {
    // uniXXXX (one BMP code point) — the common producer form.
    if let Some(hex) = name.strip_prefix(b"uni")
        && hex.len() == 4
        && let Ok(s) = std::str::from_utf8(hex)
        && let Ok(v) = u32::from_str_radix(s, 16)
    {
        return char::from_u32(v);
    }
    // uXXXX..XXXXXX
    if let Some(hex) = name.strip_prefix(b"u")
        && (4..=6).contains(&hex.len())
        && hex.iter().all(|b| b.is_ascii_hexdigit())
        && let Ok(s) = std::str::from_utf8(hex)
        && let Ok(v) = u32::from_str_radix(s, 16)
    {
        return char::from_u32(v);
    }
    if let Some(c) = standard_name_to_char(name) {
        return Some(c);
    }
    // The full Adobe Glyph List (4.3k names, binary search), then the AGL
    // rule for suffixed variants: `name.suffix` resolves as `name`.
    if let Some(c) = agl_lookup(name) {
        return Some(c);
    }
    let base = name.split(|&b| b == b'.').next().unwrap_or(name);
    if base.len() < name.len() {
        return glyph_name_to_char(base);
    }
    None
}

/// Binary search of the bundled full AGL (sorted by name).
fn agl_lookup(name: &[u8]) -> Option<char> {
    let table = crate::agl_table::AGL_NAMES;
    table
        .binary_search_by(|(n, _)| n.cmp(&name))
        .ok()
        .map(|i| table[i].1)
}

