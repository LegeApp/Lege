//! Curated Sanzo Wada theme palettes for the app's theme picker.
//!
//! Derived from *A Dictionary of Color Combinations* (Sanzo Wada). This is the
//! hand-picked subset kept from the full book set; each entry carries both a light
//! and a dark palette (lightest luma -> backgrounds, mid -> buttons, darkest -> text;
//! dark = inverse). The theme picker numbers them 1..N in array order and shows the
//! name as "Sanzo Light/Dark <n>".
use crate::appearance::Palette;

pub struct SanzoTheme {
    /// Source color names, darkest -> lightest.
    pub colors: &'static [&'static str],
    pub light: Palette,
    pub dark: Palette,
}

/// Number of curated themes; picker positions are `0..THEME_COUNT`.
pub const THEME_COUNT: usize = SANZO_THEMES.len();

/// Theme at a 0-based picker index.
pub fn theme_at(index: usize) -> Option<&'static SanzoTheme> {
    SANZO_THEMES.get(index)
}

/// Index of the theme whose source color names match `colors` exactly.
/// Used to resolve persisted themes by their stable identity, so saved
/// choices survive reordering or removal of other entries.
pub fn theme_index_by_colors(colors: &[String]) -> Option<usize> {
    SANZO_THEMES.iter().position(|theme| {
        theme.colors.len() == colors.len() && theme.colors.iter().zip(colors).all(|(a, b)| a == b)
    })
}

